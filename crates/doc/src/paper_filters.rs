#[derive(Clone, Debug, PartialEq, Serialize)]
pub struct PaperImageFilter {
    pub filter: PaperFilterKind,
    pub params: BTreeMap<String, f64>,
    pub colors: BTreeMap<String, Color>,
    pub speed: f64,
    /// Starting frame in milliseconds.
    pub frame: f64,
}
#[derive(Default, Deserialize)]
#[serde(default, deny_unknown_fields)]
struct FilterInput {
    filter: PaperFilterKind,
    params: BTreeMap<String, f64>,
    colors: BTreeMap<String, Color>,
    #[serde(default, deserialize_with = "present_speed")]
    speed: Option<f64>,
    frame: f64,
}
fn present_speed<'de, D: serde::Deserializer<'de>>(deserializer: D) -> Result<Option<f64>, D::Error> {
    // Missing uses the filter's default; an explicit null must not look like an ignored key.
    f64::deserialize(deserializer).map(Some)
}
impl<'de> Deserialize<'de> for PaperImageFilter {
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let input = FilterInput::deserialize(deserializer)?;
        let mut result = Self::new(input.filter);
        result.params = input.params;
        result.colors = input.colors;
        result.frame = input.frame;
        if let Some(speed) = input.speed {
            result.speed = speed;
        }
        Ok(result)
    }
}
impl Default for PaperImageFilter {
    fn default() -> Self {
        Self::new(PaperFilterKind::default())
    }
}
fn same_key(a: &str, b: &str) -> bool {
    a.chars().filter(|c| *c != '_').flat_map(char::to_lowercase).eq(b.chars().filter(|c| *c != '_').flat_map(char::to_lowercase))
}
impl PaperImageFilter {
    pub fn new(filter: PaperFilterKind) -> Self {
        Self { filter, params: BTreeMap::new(), colors: BTreeMap::new(), speed: if filter == PaperFilterKind::Water { 1.0 } else { 0.0 }, frame: 0.0 }
    }
    pub fn value(&self, spec: &PaperParam) -> f64 {
        let v = self.params.iter().find(|(key, _)| same_key(key, spec.name)).map(|(_, v)| *v).unwrap_or(spec.default);
        let v = if v.is_finite() { v.clamp(spec.min, spec.max) } else { spec.default };
        if spec.boolean || !spec.options.is_empty() || spec.step == 1.0 { v.round() } else { v }
    }
    pub fn color(&self, spec: &PaperColor) -> Color {
        self.colors
            .iter()
            .find(|(key, _)| same_key(key, spec.name))
            .map(|(_, c)| *c)
            .unwrap_or_else(|| Color::new(spec.default[0], spec.default[1], spec.default[2], spec.default[3]))
            .sanitized()
    }
    pub fn set_value(&mut self, name: &str, value: f64) {
        self.params.retain(|key, _| !same_key(key, name));
        self.params.insert(name.to_owned(), value);
    }
    pub fn set_color(&mut self, name: &str, color: Color) {
        self.colors.retain(|key, _| !same_key(key, name));
        self.colors.insert(name.to_owned(), color);
    }
    pub fn animated(&self) -> bool {
        self.filter == PaperFilterKind::Water && self.speed.is_finite() && self.speed != 0.0
    }
    pub fn clock(&self, time: f64) -> f32 {
        let frame = if self.frame.is_finite() { self.frame.clamp(-3.6e6, 3.6e6) * 0.001 } else { 0.0 };
        let speed = if self.speed.is_finite() { self.speed.clamp(-3.0, 3.0) } else { 0.0 };
        (frame + if time.is_finite() && self.filter == PaperFilterKind::Water { time.rem_euclid(3600.0) * speed } else { 0.0 }) as f32
    }
    pub fn validate(&self) -> Result<(), String> {
        if self.params.len() > 64 || self.colors.len() > 8 {
            return Err("too many image filter parameters".into());
        }
        for (key, value) in &self.params {
            if !value.is_finite() || !self.filter.params().iter().any(|p| same_key(key, p.name)) {
                return Err(format!("unknown or non-finite image filter parameter: {key}"));
            }
        }
        for key in self.colors.keys() {
            if !self.filter.colors().iter().any(|p| same_key(key, p.name)) {
                return Err(format!("unknown image filter color: {key}"));
            }
        }
        if !self.speed.is_finite() || !self.frame.is_finite() {
            return Err("non-finite image filter time".into());
        }
        Ok(())
    }
}
